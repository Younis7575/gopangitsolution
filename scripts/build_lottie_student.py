def g(items, name="grp"):
    """Like base.group but hoists any inline tag_tr() entries too."""
    hoisted = None
    keep = []
    for it in items:
        if isinstance(it, dict) and "__tr" in it:
            if hoisted is None:
                hoisted = it["__tr"]
        else:
            keep.append(it)
    return {"ty": "gr", "nm": name, "np": len(keep), "it": keep + [hoisted or tr()]}


# --------------------------------------------------------------- fragments ---
def check(size=30, color=CYAN, width=12):
    return g([
        path([[-size / 2, 0], [-size * 0.125, size * 0.31], [size / 2, -size * 0.34]]),
        trim(loop_draw(20, 54, LOOP - 54)),
        stroke(color, width),
    ], "check")


def dot(x, y, r, color, delay=0):
    return g([
        ellipse(r * 2, r * 2, 0, 0),
        fill(color),
        tag_tr(p=still([x, y]), o=anim([
            (delay, [0]), (delay + 14, [100]), (70, [100]), (82, [0]), (LOOP, [0]),
        ])),
    ], "dot")


def bar(x, y, w, h, color, opacity=80, delay=0, r=5):
    return g([
        rect(w, h, 0, 0, r),
        fill(color, opacity),
        tag_tr(p=still([x, y]), a=anim([
            (delay, [-w / 2, 0]), (delay + 18, [w / 2, 0]), (LOOP, [w / 2, 0]),
        ])),
    ], "bar")


def fade(delay=0, hold=70):
    return anim([(delay, [0]), (delay + 14, [100]), (hold, [100]), (hold + 12, [0]), (LOOP, [0])])


def pos3d(keys):
    """Layer positions must be 3-component vectors. A 2-component animated
    position is silently ignored by lottie-web, so the layer never moves."""
    out = []
    for i, (t, v) in enumerate(keys):
        val = list(v) + [0] if len(v) == 2 else list(v)
        if i < len(keys) - 1:
            out.append((t, val))
        else:
            out.append((t, val))
    return anim(out)


