"""
Student Project Hub — Lottie icon set.

These are generated by the SAME primitives, palette and timing curve as
scripts/build_lottie.py, so the student hub reads as part of the existing Gopang
icon system rather than a second visual language.

One local addition: `g()`. The shared group() only recognises a transform passed
via its `trs=` keyword, so a tag_tr() written inline as a shape-list item is left
behind inside `it` and never renders. g() accepts both forms and always hoists,
which keeps these icons readable without fighting the paren nesting.
"""

