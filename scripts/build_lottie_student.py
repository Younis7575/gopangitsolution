def build(name):
    layers = ICONS[name]()
    layers.sort(key=lambda l: l["ind"])
    for i, l in enumerate(layers):
        l["ind"] = i + 1
        # Icons are drawn around the origin and the layer places them on the
        # 256x256 canvas. Without this the whole composition sits in the top-left
        # corner and most of it is cropped out of the mount.
        p = l["ks"]["p"]
        if p.get("a") != 1 and p.get("k") == [0, 0, 0]:
            p["k"] = [W / 2, H / 2, 0]
    return {
        "v": "5.7.4", "fr": base.FR, "ip": 0, "op": LOOP,
        "w": W, "h": H, "nm": "gis-" + name, "ddd": 0,
        "assets": [], "layers": layers, "markers": [],
    }


def main():
    out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "lottie"
    )
    os.makedirs(out, exist_ok=True)
    total = 0
    for name in sorted(ICONS):
        data = build(name)
        path = os.path.join(out, name + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, separators=(",", ":"))
        size = os.path.getsize(path)
        total += size
        print("%-26s %2d layers  %5d B" % (name, len(data["layers"]), size))
    print("-" * 46)
    print("%d icons, %.1f KB total" % (len(ICONS), total / 1024.0))


if __name__ == "__main__":
    main()